    _textbox(slide, Inches(0.8), Inches(2.8), Inches(11.5), Inches(1.2), title, size=40, bold=True, color=RGBColor(0xFF, 0xFF, 0xFF))
    _textbox(slide, Inches(0.8), Inches(4.3), Inches(11.5), Inches(1.2), one_liner, size=22, color=RGBColor(0xD7, 0xEC, 0xE5))


